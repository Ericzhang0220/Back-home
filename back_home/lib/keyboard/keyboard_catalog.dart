import 'package:flutter/material.dart';

enum KeyboardUseScope { aiOnly, allPages }

class KeyboardSkin {
  const KeyboardSkin(
    this.characterId,
    this.name,
    this.characterName,
    this.accent,
    this.base,
    this.ink,
    this.motif,
    this.price,
    this.radius,
  );

  final String characterId;
  final String name;
  final String characterName;
  final Color accent;
  final Color base;
  final Color ink;
  final IconData motif;
  final int price;
  final double radius;
  String get id => characterId;
  String get asset => 'assets/ai_characters/$characterId.png';
  bool get isDark => base.computeLuminance() < 0.3;
}

